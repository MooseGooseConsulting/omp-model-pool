// Loopback-only relay for the optional internet smoke suite.
//
// Why this exists: pointing OMP's picker at the `smoke-…` providers restricts
// what OMP may *choose*, but it is no guarantee an SDK fallback never dials a
// real endpoint with a real key. The sandbox child is therefore only ever given
// a dummy per-run bearer and an isolated `models.yml` that routes every smoke
// provider to this relay; the relay verifies the bearer, the path, and the
// model allowlist before it considers a request admitted, and only then opens
// the single outbound connection — to the same base that served the catalog —
// carrying exactly { messages, model, stream, max_tokens } and the real
// provider credential, which never exists anywhere except inside this process.
import { randomBytes } from "node:crypto";
import { createServer } from "node:http";
import { once } from "node:events";
import { Readable } from "node:stream";

import { PROVIDER_NAMES, PROVIDERS } from "./free-routes.mjs";

export const MAX_BODY_BYTES = 1_048_576;
export const FORWARD_MAX_TOKENS = 512;
export const DEFAULT_UPSTREAM_TIMEOUT_MS = 30_000;
/** The chat URLs re-exported from the catalog map: "same bases" by construct. */
export const PROVIDER_CHAT_URLS = Object.fromEntries(
  PROVIDER_NAMES.map((provider) => [provider, PROVIDERS[provider].chatUrl]),
);

function isRecord(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

/** `kilo` → `smoke-kilo`: the OMP-facing provider names inside the sandbox. */
export function smokeProviderName(provider) {
  return `smoke-${provider}`;
}

/** Public catalog selector → isolated selector, or null when it is not a smoke route. */
export function toSmokeSelector(publicSelector) {
  if (typeof publicSelector !== "string") return null;
  const slash = publicSelector.indexOf("/");
  if (slash <= 0) return null;
  const provider = publicSelector.slice(0, slash);
  if (!PROVIDER_NAMES.includes(provider)) return null;
  return `${smokeProviderName(provider)}/${publicSelector.slice(slash + 1)}`;
}

/** Transcript identity `smoke-<provider>/<id>` → public catalog selector, or null. */
export function publicSelectorFromSmokeIdentity(identity) {
  if (typeof identity !== "string") return null;
  const slash = identity.indexOf("/");
  if (slash <= 0) return null;
  const provider = identity.slice(0, slash);
  if (!PROVIDER_NAMES.includes(provider.slice("smoke-".length))) return null;
  if (provider !== smokeProviderName(provider.slice("smoke-".length))) return null;
  return `${provider.slice("smoke-".length)}/${identity.slice(slash + 1)}`;
}

function positiveIntegerOr(value, fallback) {
  const n = typeof value === "number" ? value : typeof value === "string" && value.trim() !== "" ? Number(value) : Number.NaN;
  return Number.isFinite(n) && Number.isInteger(n) && n > 0 ? n : fallback;
}

/**
 * Render the sandbox `models.yml`: one provider entry per provider that owns a
 * member of the trio, with only the verified concrete catalog ids as static
 * rows and the per-run dummy bearer. The public catalog selectors are recorded
 * in comments; OMP only ever sees the `smoke-…` names.
 */
export function renderSmokeProvidersYaml({ routes, bearer, port }) {
  const byProvider = new Map();
  for (const route of routes) {
    if (!PROVIDER_NAMES.includes(route.provider)) {
      throw new TypeError(`renderSmokeProvidersYaml: unknown provider ${route.provider}`);
    }
    if (!byProvider.has(route.provider)) byProvider.set(route.provider, []);
    byProvider.get(route.provider).push(route);
  }
  const lines = [
    "# generated by test/live — isolated smoke providers backed by the loopback relay.",
    `# Public catalog selectors ${PROVIDER_NAMES.map((p) => `${p}/<id>:free`).join(" and ")} map onto these names;`,
    "# the relay only replaces the bearer and the upstream base.",
    "providers:",
  ];
  for (const provider of PROVIDER_NAMES) {
    const rows = byProvider.get(provider);
    if (rows === undefined) continue;
    lines.push(
      `  ${smokeProviderName(provider)}:`,
      `    baseUrl: http://127.0.0.1:${port}/${provider}/v1`,
      "    api: openai-completions",
      `    apiKey: ${bearer}`,
      "    models:",
    );
    const sorted = [...rows].sort((a, b) => a.catalogId.localeCompare(b.catalogId));
    for (const row of sorted) {
      const contextWindow = positiveIntegerOr(row.entry?.context_length, 64_000);
      const maxTokens = Math.max(positiveIntegerOr(row.entry?.max_completion_tokens, 1024), 1024);
      lines.push(
        `      - id: "${row.catalogId}"`,
        `        name: "${row.catalogId}"`,
        "        # public selector: " + row.selector,
        "        input: [text]",
        `        contextWindow: ${contextWindow}`,
        `        maxTokens: ${maxTokens}`,
        "        reasoning: false",
      );
    }
  }
  if (lines.length === 3) {
    throw new TypeError("renderSmokeProvidersYaml: routes contained no kilo/openrouter rows");
  }
  return `${lines.join("\n")}\n`;
}

function respondJson(res, status, message) {
  if (res.headersSent || res.writableEnded || res.destroyed) return;
  res.writeHead(status, { "content-type": "application/json", connection: "close" });
  res.end(JSON.stringify({ error: { message } }));
}

/** Collect (capped) request body; `ok:false` when the client vanished or the body ran past the cap. */
function readRequestBody(req, limit = MAX_BODY_BYTES) {
  return new Promise((resolve) => {
    const chunks = [];
    let size = 0;
    let settled = false;
    const settle = (value) => {
      if (settled) return;
      settled = true;
      resolve(value);
    };
    req.on("error", () => settle({ ok: false, text: "" }));
    req.on("aborted", () => settle({ ok: false, text: "" }));
    req.on("data", (chunk) => {
      if (settled) return;
      size += chunk.length;
      if (size > limit) {
        settle({ ok: false, tooLarge: true, text: "" });
        return;
      }
      chunks.push(chunk);
    });
    req.on("end", () => settle({ ok: true, text: Buffer.concat(chunks).toString("utf8") }));
  });
}

/**
 * Start the relay on a random loopback port.
 *
 * `routes` are the verified trio from free-routes; `providerKeys` maps
 * kilo/openrouter to the invoking environment's real keys and never leaves
 * this module except inside outbound authorization headers. `fetchImpl` exists
 * for the offline unit tests; production callers use the platform default.
 */
export async function createFreeGateway({
  routes,
  providerKeys,
  bearer,
  upstreamTimeoutMs = DEFAULT_UPSTREAM_TIMEOUT_MS,
  fetchImpl,
  log = () => {},
} = {}) {
  if (!Array.isArray(routes) || routes.length === 0) {
    throw new TypeError("createFreeGateway: routes must be a nonempty list of verified routes");
  }
  const allowByProvider = new Map();
  for (const provider of PROVIDER_NAMES) allowByProvider.set(provider, new Set());
  const selectorByRoute = new Map();
  for (const route of routes) {
    if (!isRecord(route) || !PROVIDER_NAMES.includes(route.provider) || typeof route.catalogId !== "string") {
      throw new TypeError(`createFreeGateway: not a verified route: ${JSON.stringify(route ?? null)}`);
    }
    allowByProvider.get(route.provider).add(route.catalogId);
    selectorByRoute.set(`${route.provider}\u0000${route.catalogId}`, route.selector);
  }

  const runBearer =
    typeof bearer === "string" && bearer.length > 0 ? bearer : `smoke-${randomBytes(24).toString("hex")}`;

  const counts = { admitted: 0, bySelector: new Map() };
  function slotFor(provider, catalogId) {
    const selector = selectorByRoute.get(`${provider}\u0000${catalogId}`);
    let slot = counts.bySelector.get(selector);
    if (slot === undefined) {
      slot = { admitted: 0, statuses: [] };
      counts.bySelector.set(selector, slot);
    }
    return slot;
  }

  const upstreamControllers = new Set();

  async function handleRequest(req, res) {
    const pathname = new URL(req.url ?? "/", "http://127.0.0.1").pathname;
    if (req.method !== "POST") {
      return respondJson(res, 405, "smoke relay: only POST is served");
    }
    const match = /^\/(kilo|openrouter)\/v1\/chat\/completions$/.exec(pathname);
    if (match === null) {
      return respondJson(res, 404, "smoke relay: only /<provider>/v1/chat/completions is served");
    }
    const provider = match[1];
    const upstreamKey = providerKeys?.[provider];
    if (typeof upstreamKey !== "string" || upstreamKey.trim().length === 0) {
      return respondJson(res, 500, "smoke relay: no upstream credential for this provider (suite misconfiguration)");
    }
    const auth = req.headers.authorization;
    if (typeof auth !== "string" || auth !== `Bearer ${runBearer}`) {
      return respondJson(res, 401, "smoke relay: bearer mismatch");
    }
    const declared = Number(req.headers["content-length"]);
    if (Number.isFinite(declared) && declared > MAX_BODY_BYTES) {
      return respondJson(res, 413, "smoke relay: request body too large");
    }
    const read = await readRequestBody(req);
    if (!read.ok) {
      if (read.tooLarge) return respondJson(res, 413, "smoke relay: request body too large");
      return; // client vanished mid-body; nothing to answer
    }
    let parsed;
    try {
      parsed = JSON.parse(read.text);
    } catch {
      return respondJson(res, 400, "smoke relay: request body is not valid JSON");
    }
    if (!isRecord(parsed) || typeof parsed.model !== "string" || parsed.model.length === 0) {
      return respondJson(res, 400, "smoke relay: request carries no model");
    }
    if (!allowByProvider.get(provider).has(parsed.model)) {
      log(`[smoke-relay] rejected HTTP 403 — model ${parsed.model} is not on the ${provider} allowlist`);
      return respondJson(res, 403, "smoke relay: model is not on the verified free-route allowlist");
    }
    if (
      !Array.isArray(parsed.messages) ||
      parsed.messages.length === 0 ||
      parsed.messages.some((message) => !isRecord(message) || typeof message.role !== "string")
    ) {
      return respondJson(res, 400, "smoke relay: not a chat completions request shape");
    }

    // Admitted. This is the only code path that ever attempts an outbound
    // connection: no syn/CONNECT/anything before this line.
    const slot = slotFor(provider, parsed.model);
    slot.admitted += 1;
    counts.admitted += 1;
    log(`[smoke-relay] admitted ${selectorByRoute.get(`${provider}\u0000${parsed.model}`)} → upstream ${provider}`);

    const controller = new AbortController();
    upstreamControllers.add(controller);
    let deadlineHit = false;
    const deadline = setTimeout(() => {
      deadlineHit = true;
      controller.abort(new Error("smoke relay: upstream deadline exceeded"));
    }, upstreamTimeoutMs);
    deadline.unref?.();
    const finish = () => {
      clearTimeout(deadline);
      upstreamControllers.delete(controller);
    };
    res.on("close", () => {
      if (!res.writableEnded) controller.abort(new Error("smoke relay: client disconnected"));
    });

    // Exactly four fields; the client's other fields (tools, router/fallback
    // bodies, stream options, provider hints) and headers are never forwarded,
    // so no SDK fallback path can ride along.
    const forwarded = { messages: parsed.messages, model: parsed.model, stream: true, max_tokens: FORWARD_MAX_TOKENS };
    let upstream;
    try {
      const fetchFn = typeof fetchImpl === "function" ? fetchImpl : globalThis.fetch;
      if (typeof fetchFn !== "function") throw new Error("no fetch implementation");
      upstream = await fetchFn(PROVIDER_CHAT_URLS[provider], {
        method: "POST",
        headers: {
          "content-type": "application/json",
          accept: "text/event-stream",
          authorization: `Bearer ${upstreamKey.trim()}`,
        },
        body: JSON.stringify(forwarded),
        redirect: "error",
        signal: controller.signal,
      });
    } catch (err) {
      const status = deadlineHit
        ? "timeout"
        : err !== null && typeof err === "object" && err.name === "AbortError"
          ? "client-disconnect"
          : "error";
      slot.statuses.push(status);
      log(`[smoke-relay] upstream failure (${status}) for ${selectorByRoute.get(`${provider}\u0000${parsed.model}`)}`);
      finish();
      if (!res.writableEnded && !res.destroyed && !res.headersSent) {
        return respondJson(res, deadlineHit ? 504 : 502, `smoke relay: upstream failed (${status})`);
      }
      return;
    }
    slot.statuses.push(upstream.status);
    if (!upstream.ok) {
      log(`[smoke-relay] ${selectorByRoute.get(`${provider}\u0000${parsed.model}`)} → upstream HTTP ${upstream.status}`);
      finish();
      return respondJson(res, upstream.status, "smoke relay: the provider rejected the admitted request");
    }
    if (res.writableEnded || res.destroyed) {
      finish();
      return;
    }

    // Pipe the SSE stream and the content type straight through. The upstream
    // deadline stays armed until the body is fully consumed: a provider that
    // sends headers promptly and then stalls would otherwise never be aborted,
    // and the run would sit until the harness's process timeout instead.
    const contentType = upstream.headers?.get?.("content-type");
    res.writeHead(200, { "cache-control": "no-store", "content-type": contentType ?? "text/event-stream" });
    if (upstream.body === null || upstream.body === undefined) {
      finish();
      res.end();
      return;
    }
    try {
      const source = Readable.fromWeb(upstream.body);
      for await (const chunk of source) {
        if (res.writableEnded || res.destroyed) break;
        if (!res.write(chunk)) {
          // Race drain against teardown: a vanished client must not leave this loop parked.
          await Promise.race([once(res, "drain"), once(res, "close")]);
        }
      }
      if (!res.writableEnded && !res.destroyed) res.end();
    } catch {
      // A broken stream after the headers is not classifiable as a provider
      // skip; the transcript and exit code decide. A body that stalled past the
      // deadline is recorded so the caller can treat it as a timeout.
      if (deadlineHit) slot.statuses.push("timeout");
      if (!res.writableEnded && !res.destroyed) res.end();
    } finally {
      // Only now can the controller and its timer be retired.
      finish();
    }
  }

  const server = createServer((req, res) => {
    handleRequest(req, res).catch(() => {
      // Last-resort guard so a handler bug surfaces as a status code, never as
      // an unhandled rejection in the suite process.
      try {
        respondJson(res, 500, "smoke relay: internal error");
      } catch {
        // socket already gone
      }
    });
  });
  server.unref?.();
  await new Promise((resolve, reject) => {
    server.once("error", reject);
    server.listen(0, "127.0.0.1", () => {
      server.removeListener("error", reject);
      resolve(undefined);
    });
  });
  const address = server.address();
  const port = typeof address === "object" && address !== null ? address.port : 0;
  if (typeof port !== "number" || port <= 0) {
    server.close();
    throw new Error("createFreeGateway: the relay did not bind a usable loopback port");
  }

  return {
    port,
    url: `http://127.0.0.1:${port}`,
    bearer: runBearer,
    snapshot() {
      const bySelector = {};
      for (const [selector, slot] of counts.bySelector) {
        bySelector[selector] = { admitted: slot.admitted, statuses: [...slot.statuses] };
      }
      return { admitted: counts.admitted, bySelector };
    },
    async close() {
      for (const controller of upstreamControllers) {
        try {
          controller.abort(new Error("smoke relay closing"));
        } catch {
          // already aborted
        }
      }
      upstreamControllers.clear();
      try {
        server.closeAllConnections?.();
      } catch {
        // nothing connected
      }
      await new Promise((resolve) => {
        server.close(() => resolve());
      });
    },
  };
}
